import {expect,worldTest} from '@gameengine/test';
import campaign from '../data/levels.json';
import {createPartyGame} from '../src/arcade/party';
import {createGame} from '../src/arcade/game';
import {hurtPlayer} from '../src/arcade/player';
import {cartoonHudModel} from '../src/cartoon/hud-model';
import {initialDesktopSave} from '../src/desktop/save';

worldTest('cartoon roster reports actual downed teammates as rescuable and preserves ten stable identities',()=>{
  const g=createPartyGame(campaign,42,['human','ai','human','ai','empty','ai','ai','ai','ai','human'],10,'cartoon');
  g.Players[2]!.Invincible=0;hurtPlayer(g,2);
  expect(g.Players[2]!.Lives).toBe(0);
  expect(g.Players[2]!.Downed).toBe(true);
  Object.assign(g.Players[3]!,{Dead:30,Lives:1});
  Object.assign(g.Players[5]!,{Lives:0,Downed:false,Dead:0});
  expect(g.Players.length).toBe(10);
  expect(g.Players[4]!.Lives).toBe(0);
  const before=JSON.stringify(g),saveBefore=JSON.stringify(initialDesktopSave);
  const model=cartoonHudModel(g,initialDesktopSave);
  const roster=[...model.rosterTop!,...model.rosterBottom!];
  expect(model.rosterTop!.length).toBe(5);expect(model.rosterBottom!.length).toBe(5);
  expect(new Set(roster.map(slot=>slot.key)).size).toBe(10);
  expect(roster[0]!.status).toBe('PLAYER 1');expect(roster[1]!.status).toBe('AI TEAMMATE');
  expect(roster[2]!.condition).toBe('rescue');expect(roster[2]!.number).toBe('3');expect(roster[2]!.color).toBe('red');
  expect(roster[2]!.status).toBe('RESCUE ME!');expect(roster[2]!.down).toBe(true);
  expect(roster[3]!.condition).toBe('returning');expect(roster[3]!.status).toBe('RETURNING');expect(roster[3]!.down).toBe(true);
  expect(roster[4]!.condition).toBe('open');expect(roster[4]!.status).toBe('OPEN SLOT');expect(roster[4]!.active).toBe(false);
  expect(roster[4]!.down).toBe(false);
  expect(roster[4]!.portrait).toBe('cartoon/reconstruction/ui/portraits/purple');
  expect(roster[5]!.condition).toBe('out');expect(roster[5]!.status).toBe('OUT');expect(roster[5]!.active).toBe(true);
  expect(roster[9]!.key).toBe('dragon-9');expect(roster[9]!.status).toBe('PLAYER 10');
  expect(roster[9]!.portrait).toBe('cartoon/reconstruction/ui/portraits/slate');
  expect(new Set(roster.map(slot=>slot.portrait)).size).toBe(10);
  expect(JSON.stringify(g)).toBe(before);expect(JSON.stringify(initialDesktopSave)).toBe(saveBefore);
  const classic=createGame(campaign,42);
  const save={...initialDesktopSave,profiles:initialDesktopSave.profiles.map(profile=>({...profile,avatar:'blue' as const}))};
  const classicHud=cartoonHudModel(classic,save);
  expect(classicHud.classicPortrait).toBe('cartoon/reconstruction/ui/portraits/blue');
  expect(classicHud.rosterTop).toBe(undefined);
},{scene:'scenes/arcade.scene.json'});
